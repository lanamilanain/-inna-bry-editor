-- Секретное дело № 31 · Supabase setup
create table if not exists public.advent_days (
  id bigint generated by default as identity primary key,
  day_number int not null unique check (day_number between 1 and 31),
  title text default '',
  letter_title text default '',
  letter_body text default '',
  task text default '',
  extra_text text default '',
  image_url text,
  video_url text,
  audio_url text,
  is_published boolean not null default false,
  updated_at timestamptz not null default now()
);
create table if not exists public.child_messages (
  id bigint generated by default as identity primary key,
  day_number int not null check (day_number between 1 and 31),
  message text not null check (char_length(message) between 1 and 3000),
  created_at timestamptz not null default now()
);
insert into public.advent_days(day_number)
select generate_series(1,31)
on conflict (day_number) do nothing;

alter table public.advent_days enable row level security;
alter table public.child_messages enable row level security;

-- Admin accounts are explicitly listed by user UUID in this table.
create table if not exists public.advent_admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.advent_admins enable row level security;
create or replace function public.is_advent_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.advent_admins where user_id = auth.uid()) $$;

create policy "Public can read published days" on public.advent_days
for select to anon, authenticated using (is_published or public.is_advent_admin());
create policy "Admins manage days" on public.advent_days
for all to authenticated using (public.is_advent_admin()) with check (public.is_advent_admin());
create policy "Visitors can send messages" on public.child_messages
for insert to anon, authenticated with check (true);
create policy "Admins read messages" on public.child_messages
for select to authenticated using (public.is_advent_admin());
create policy "Admins manage admin list" on public.advent_admins
for all to authenticated using (public.is_advent_admin()) with check (public.is_advent_admin());

insert into storage.buckets (id, name, public, file_size_limit)
values ('advent-media','advent-media',true,52428800)
on conflict (id) do update set public=true, file_size_limit=52428800;
create policy "Public reads advent media" on storage.objects
for select to anon, authenticated using (bucket_id='advent-media');
create policy "Admins upload advent media" on storage.objects
for insert to authenticated with check (bucket_id='advent-media' and public.is_advent_admin());
create policy "Admins update advent media" on storage.objects
for update to authenticated using (bucket_id='advent-media' and public.is_advent_admin()) with check (bucket_id='advent-media' and public.is_advent_admin());
create policy "Admins delete advent media" on storage.objects
for delete to authenticated using (bucket_id='advent-media' and public.is_advent_admin());
